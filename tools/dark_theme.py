def swap(value, table):
    out = value
    for k in sorted(table, key=len, reverse=True):
        out = re.sub(r'(?<![\w#-])' + re.escape(k) + r'(?![\w-])', table[k], out, flags=re.I)
    return out


def rules(css):
    """Yield (media_prefix, selector, body) for every style rule, descending one level into @media."""
    i = 0
    while i < len(css):
        j = css.find('{', i)
        if j < 0:
            return
        head = css[i:j].strip()
        depth, k = 1, j + 1
        while depth and k < len(css):
            depth += (css[k] == '{') - (css[k] == '}'); k += 1
        body = css[j + 1:k - 1]
        if head.startswith('@media'):
            for _, sel, b in rules(body):
                yield head, sel, b
        elif not head.startswith('@') and head:
            yield None, head, body
        i = k


def convert(sel, body):
    decls = [d.strip() for d in body.split(';') if ':' in d]
    props = {d.split(':', 1)[0].strip().lower(): d.split(':', 1)[1].strip() for d in decls}
    out = []
    light_text = any(re.search(r'white|#fff\b|var\(--lime\)', props.get(p, '')) for p in ('color',))
    lime_bg = re.search(r'var\(--lime\)|#d6f46a|#c9ea4f', props.get('background', '') + props.get('background-color', ''))
    for d in decls:
        p, v = (x.strip() for x in d.split(':', 1))
        pl = p.lower()
        nv = v
        if pl in ('background', 'background-color'):
            nv = swap(v, BG)
            if 'var(--ink)' in v:
                key = next((k for k in INK_BG if k in sel), None)
                if key is None:
                    nv = nv.replace('var(--ink)', '#24406b')
                elif INK_BG[key]:
                    nv = nv.replace('var(--ink)', INK_BG[key])
        elif pl == 'color':
            nv = swap(v, TEXT)
            if lime_bg and 'var(--ink)' in v:
                nv = '#162840'
        elif pl.startswith('border') or pl in ('outline', 'box-shadow'):
            nv = swap(v, BORDER)
            if pl == 'box-shadow':
                nv = re.sub(r'#fff\b', '#15233a', nv)
            if pl.startswith('border') and 'var(--ink)' in v and ('#24406b' in ' '.join(out) or 'var(--ink)' in props.get('background', '')):
                nv = v.replace('var(--ink)', '#24406b')
        if nv != v:
            out.append(f'{p}:{nv}')
    if not out:
        return None
    sels = []
    for s in sel.split(','):
        s = s.strip()
        if s.startswith(':root'):
            continue
        sels.append(f'{D} {s}' if not s.startswith('html') else s.replace('html', D, 1))
    return (','.join(sels), ';'.join(out)) if sels else None


def main():
    css = CSS.read_text(encoding='utf-8')
    if START in css:
        css = css[:css.index(START)].rstrip() + '\n'
    lines, n = [START, ROOT.strip()], 0
    for media, sel, body in rules(css):
        r = convert(sel, body)
        if not r:
            continue
        n += 1
        rule = f'{r[0]}{{{r[1]}}}'
        lines.append(f'{media}{{{rule}}}' if media else rule)
    lines.append(END)
    CSS.write_text(css + '\n' + '\n'.join(lines) + '\n', encoding='utf-8', newline='')
    print(f'dark overrides: {n} rules')


if __name__ == '__main__':
    main()
